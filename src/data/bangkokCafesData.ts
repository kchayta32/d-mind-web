/**
 * Utility helper to generate standard 7-day schedule with optional day overrides
 */
function buildSchedule(
  defaultOpen: string,
  defaultClose: string,
  closedDays: DayOfWeek[] = [],
  overrides: Partial<Record<DayOfWeek, { open: string; close: string }>> = {}
): WeeklySchedule {
  const days: DayOfWeek[] = ['mon', 'tue', 'wed', 'thu', 'fri', 'sat', 'sun'];
  const schedule = {} as WeeklySchedule;

  for (const day of days) {
    if (closedDays.includes(day)) {
      schedule[day] = [{ open: '00:00', close: '00:00', isClosed: true }];
    } else if (overrides[day]) {
      schedule[day] = [{ open: overrides[day]!.open, close: overrides[day]!.close, isClosed: false }];
    } else {
      schedule[day] = [{ open: defaultOpen, close: defaultClose, isClosed: false }];
    }
  }

  return schedule;
}

