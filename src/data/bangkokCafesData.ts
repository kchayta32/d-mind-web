/**
 * Checks if given time string (e.g. '14:30') falls within the venue's schedule for that day.
 * Handles both daytime operations and overnight bar schedules (e.g. 18:00 - 01:30).
 */
export function checkIsOpen(venue: CafeVenue, targetDay: DayOfWeek, targetTime: string): boolean {
  if (!venue || !venue.schedule) return false;

  const daySchedule: TimeSlot[] | undefined = venue.schedule[targetDay];
  if (!daySchedule || daySchedule.length === 0) return false;

  // Format validation: expects HH:mm or HH:mm:ss
  const match = targetTime.trim().match(/^(\d{1,2}):(\d{2})/);
  if (!match) return false;

  const targetMinutes = parseInt(match[1], 10) * 60 + parseInt(match[2], 10);

  for (const slot of daySchedule) {
    if (slot.isClosed) continue;

    const openMatch = slot.open.match(/^(\d{1,2}):(\d{2})/);
    const closeMatch = slot.close.match(/^(\d{1,2}):(\d{2})/);

    if (!openMatch || !closeMatch) continue;

    const openMinutes = parseInt(openMatch[1], 10) * 60 + parseInt(openMatch[2], 10);
    const closeMinutes = parseInt(closeMatch[1], 10) * 60 + parseInt(closeMatch[2], 10);

    if (closeMinutes > openMinutes) {
      // Standard daytime schedule (e.g., 08:00 to 18:00)
      if (targetMinutes >= openMinutes && targetMinutes < closeMinutes) {
        return true;
      }
    } else if (closeMinutes < openMinutes) {
      // Overnight schedule crossing midnight (e.g., 18:00 to 02:00)
      if (targetMinutes >= openMinutes || targetMinutes < closeMinutes) {
        return true;
      }
    } else {
      // open === close: if 00:00 - 00:00 and not marked closed, treat as 24-hr open
      if (!slot.isClosed && slot.open === '00:00') {
        return true;
      }
    }
  }

  return false;
}

/**
 * Calculate dynamic flood safety score based on venue base risk, nearby flooded roads,
 * indoor seating capacity, and district infrastructure.
 */
export function calculateFloodSafetyScore(
  venue: CafeVenue,
  nearbyFloodedRoadsCount: number
): FloodSafetyEvaluation {
  // Baseline score by venue's inherent area flood risk
  let baseScore = 95;
  if (venue.floodRisk === 'moderate') {
    baseScore = 65;
  } else if (venue.floodRisk === 'risk') {
    baseScore = 35;
  }

  // Deduct points for nearby flooded roads (12 points per flooded road segment)
  const roadPenalty = Math.min(nearbyFloodedRoadsCount * 12, 40);
  let finalScore = baseScore - roadPenalty;

  // Bonus for fully indoor seating & covered parking stability (+5)
  if (venue.indoorSeating && venue.hasParking) {
    finalScore += 5;
  }

  // Clamp score between 0 and 100
  finalScore = Math.max(5, Math.min(100, Math.round(finalScore)));

  // Derive dynamic status
  let status: FloodRiskLevel = 'safe';
  let reason = '';

  if (finalScore >= 80) {
    status = 'safe';
    if (nearbyFloodedRoadsCount === 0) {
      reason = 'ปลอดภัยสูง พื้นที่ระบายน้ำดีเยี่ยม ไม่มีถนนน้ำท่วมขังในรัศมี 2 กม.';
    } else {
      reason = `ปลอดภัย ตัวร้านยกสูง แม้มีรายงานน้ำขังเล็กน้อยในพื้นที่ใกล้เคียง (${nearbyFloodedRoadsCount} จุด)`;
    }
  } else if (finalScore >= 50) {
    status = 'moderate';
    if (nearbyFloodedRoadsCount > 0) {
      reason = `เฝ้าระวัง มีถนนน้ำท่วมขังใกล้เคียง ${nearbyFloodedRoadsCount} เส้นทาง แนะนำเลี่ยงเส้นทางย่อย`;
    } else {
      reason = 'เฝ้าระวัง พื้นที่เคยมีประวัติน้ำรอระบายช่วงฝนตกหนักต่อเนื่อง';
    }
  } else {
    status = 'risk';
    reason = `จุดเสี่ยงน้ำท่วมสูง ตรวจพบถนนน้ำท่วมขังใกล้เคียง ${nearbyFloodedRoadsCount} จุด หรืออยู่ในพื้นที่ลุ่มต่ำริมคลอง`;
  }

  return {
    score: finalScore,
    status,
    reason,
  };
}
